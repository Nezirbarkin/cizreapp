#   Her yerel migration'i uzak gecmis tablosuna "applied" olarak ISARETLER.
#   HICBIR SQL CALISTIRMAZ, semaya DOKUNMAZ. Yalnizca
#   supabase_migrations.schema_migrations tablosuna kayit duser.
#
# ON KOSUL
#   Uretim semasi bu migration'larin TAMAMINI zaten icermeli. 2026-08-16
#   teshisinde uc eksik bulundu, once onlar SQL Editor'den uygulanmali:
#     * 20260802000001_secure_add_to_balance_and_courier_refund.sql
#     * 20260817000020_restore_admin_rpc_execute_grants.sql
#     * 20260817000029_group_admin_rpcs_from_production.sql
#   Dogrulama: supabase/diagnostics/20260816_admin_panel_rpc_drift.sql
#   bu betikten ONCE "0 satir" dondurmeli.
#
# CALISTIRMA
#   bash supabase/scripts/repair_migration_history.sh
#
# SONRASI
#   `supabase migration list` -> her satirda Local ve Remote dolu olmali.
#   Bundan sonra yeni migration'lar normal `supabase db push` ile gider.
# =============================================================================
